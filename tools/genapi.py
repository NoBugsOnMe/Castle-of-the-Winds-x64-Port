#!/usr/bin/env python3
"""Generate the Win16 import thunk table for the functions CotW imports."""
import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from nedump import NE
from specmap import specs
SIZES={'word':2,'s_word':2,'long':4,'ptr':4,'segptr':4,'str':4,'segstr':4}
imports=set()
for path in sys.argv[1:]:
    n=NE(path)
    for s in n.segs:
        for r in n.relocs(s):
            if r['flags']&3==1: imports.add((n.mods[r['a']-1], r['c']))
rows=[]
for mod,o in sorted(imports):
    kind,name,args,impl=specs[mod][o]
    if kind=='equate': continue
    argl=args.split() if args else []
    size=sum(SIZES[a] for a in argl)
    if kind=='stub': size={'FatalExit':2}.get(name,0)
    rows.append((mod,o,name,size,argl))
out=open(__import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)), '..', 'gen', 'apitab.c'),'w')
out.write('/* generated by tools/genapi.py - Win16 functions imported by CASTLE1/CASTLE2 */\n#include "../src/win16.h"\n\n')
for mod,o,name,size,argl in rows:
    out.write('void %s_%s(void);\n'%(mod,name))
out.write('\nconst ApiEntry g_api_table[] = {\n')
for mod,o,name,size,argl in rows:
    out.write('    { "%s", %d, "%s", %d, %s_%s },\n'%(mod,o,name,size,mod,name))
out.write('    { 0, 0, 0, 0, 0 }\n};\n')
out.close()
print(len(rows),'functions')
for mod,o,name,size,argl in rows: print(mod,o,name,size,' '.join(argl))
